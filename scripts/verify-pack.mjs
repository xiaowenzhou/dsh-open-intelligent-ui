import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, access } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const temporary = await mkdtemp(path.join(tmpdir(), 'dsh-ui-pack-'));
const consumer = path.join(temporary, 'consumer');
await mkdir(consumer);
const env = { ...process.env, NODE_PATH: '', NODE_OPTIONS: '' };
function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, env, encoding: 'utf8', shell: process.platform === 'win32' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed (${result.status}):\n${result.stdout}\n${result.stderr}`);
  return result.stdout;
}
// An earlier check/build is required. Packing here skips hooks to avoid running checks twice.
const output = run('npm', ['pack', '--ignore-scripts', '--json', '--pack-destination', temporary], root);
const packed = JSON.parse(output)[0];
const tarball = path.join(temporary, packed.filename);
await writeFile(path.join(consumer, 'package.json'), JSON.stringify({ name: 'dsh-ui-package-smoke', private: true, type: 'module' }));
run('npm', ['install', tarball, '--omit=dev', '--ignore-scripts', '--no-audit', '--no-fund', '--fetch-retries=0', '--fetch-timeout=30000'], consumer);
const code = `
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const name = ${JSON.stringify(manifest.name)};
const require = createRequire(import.meta.url);
const host = await import(name);
assert.equal(typeof host.apply, 'function');
const tools = [];
host.apply({ tools: { register: tool => tools.push(tool) }, systemPrompt: { section: () => {} } });
assert.deepEqual(tools.map(tool => tool.name), ['intelligent_ui_guide', 'render_intelligent_ui']);
assert.match((await tools[0].execute({})).guide, /Dashboard/);
const value = await tools[1].execute({ title: 'Package smoke', program: 'root = Dashboard([])' });
assert.equal(tools[1].output.presentationMeta({}, value).intelligentUi.version, 1);
for (const suffix of ['/icon', '/locale/en.json', '/locale/zh.json']) assert.ok(existsSync(fileURLToPath(import.meta.resolve(name + suffix))));
const clientPath = fileURLToPath(import.meta.resolve(name + '/client'));
assert.ok(existsSync(path.resolve(path.dirname(clientPath), '../cordis.patch.yml')));
let descriptor;
new Function('window', readFileSync(clientPath, 'utf8'))({ __ModuleLoader__: { load: entry => { descriptor = entry; } } });
assert.equal(descriptor.id, name);
const registrations = [];
descriptor.factory(require).apply({ locale: { register: () => {} }, sessions: {}, slots: { inject: (_key, callback) => callback(), register: entry => registrations.push(entry) } });
assert.deepEqual(registrations.map(entry => entry.name), ['tool.call.toolview', 'conversation.input.left']);
assert.ok(require.resolve('react').startsWith(process.cwd()));
assert.ok(!existsSync('node_modules/esbuild'));
console.log('Clean production tarball install: Host tools, guide, metadata, Client slots, locales and icon verified.');
`;
await writeFile(path.join(consumer, 'smoke.mjs'), code);
console.log(run(process.execPath, ['smoke.mjs'], consumer).trim());
console.log(`Package: ${tarball}`);
console.log(`Packed size: ${packed.size} bytes; files: ${packed.entryCount}`);
console.log(`Consumer kept for inspection: ${consumer}`);
await access(tarball);
